def _section(story: list[object], title: str, styles: dict[str, ParagraphStyle]) -> None:
    story.append(Paragraph(escape(title), styles["heading"]))


def _warning_box(value: str, styles: dict[str, ParagraphStyle]) -> Table:
    table = Table([[Paragraph(escape(value), styles["warning"])]], colWidths=(172 * mm,))
    table.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#FEF3C7")),
                ("BOX", (0, 0), (-1, -1), 0.8, colors.HexColor("#F59E0B")),
                ("LEFTPADDING", (0, 0), (-1, -1), 10),
                ("RIGHTPADDING", (0, 0), (-1, -1), 10),
                ("TOPPADDING", (0, 0), (-1, -1), 10),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 10),
            ]
        )
    )
    return table


def _key_value_table(
    items: tuple[tuple[str, str], ...], styles: dict[str, ParagraphStyle]
) -> Table:
    rows = [
        [
            Paragraph(f"<b>{escape(label)}</b>", styles["table"]),
            Paragraph(escape(value), styles["table"]),
        ]
        for label, value in items
    ]
    table = Table(rows, colWidths=(46 * mm, 126 * mm), repeatRows=0)
    table.setStyle(
        TableStyle(
            [
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#F1F5F9")),
                ("GRID", (0, 0), (-1, -1), 0.35, colors.HexColor("#CBD5E1")),
                ("LEFTPADDING", (0, 0), (-1, -1), 6),
                ("RIGHTPADDING", (0, 0), (-1, -1), 6),
                ("TOPPADDING", (0, 0), (-1, -1), 5),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
            ]
        )
    )
    return table


def _data_table(
    rows: list[list[str]], widths: tuple[float, ...], styles: dict[str, ParagraphStyle]
) -> Table:
    rendered = [[Paragraph(escape(str(value)), styles["table"]) for value in row] for row in rows]
    table = Table(rendered, colWidths=widths, repeatRows=1)
    table.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#164E63")),
                ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
                ("GRID", (0, 0), (-1, -1), 0.3, colors.HexColor("#CBD5E1")),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ("ROWBACKGROUNDS", (0, 1), (-1, -1), (colors.white, colors.HexColor("#F8FAFC"))),
                ("LEFTPADDING", (0, 0), (-1, -1), 4),
                ("RIGHTPADDING", (0, 0), (-1, -1), 4),
                ("TOPPADDING", (0, 0), (-1, -1), 4),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
            ]
        )
    )
    return table


def _footer(pdf: canvas.Canvas, document: object) -> None:
    page_number = getattr(document, "page", 1)
    pdf.saveState()
    pdf.setStrokeColor(colors.HexColor("#CBD5E1"))
    pdf.line(18 * mm, 14 * mm, 192 * mm, 14 * mm)
    pdf.setFont("Helvetica-Bold", 7)
    pdf.setFillColor(colors.HexColor("#B45309"))
    pdf.drawString(18 * mm, 9 * mm, "PRELIMINARY - CONTROLLED LOGICAL TRIAGE")
    pdf.setFont("Helvetica", 7)
    pdf.setFillColor(colors.HexColor("#64748B"))
    pdf.drawRightString(192 * mm, 9 * mm, f"Page {page_number}")
    pdf.restoreState()
